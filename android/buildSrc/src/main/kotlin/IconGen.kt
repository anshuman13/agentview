package no.pradhan.agentview.tokens

// Turns @vscode/codicons codicon.css into a Kotlin name to codepoint table. The css has the aliases (clock, git-branch) that codicon.csv leaves out.
object IconGen {
    private val rule = Regex("""\.codicon-([a-z0-9-]+):before\s*\{\s*content:\s*"\\([0-9a-f]+)"""")

    fun parse(css: String): List<Pair<String, Int>> = rule.findAll(css).map { it.groupValues[1] to it.groupValues[2].toInt(16) }.toList()

    private val line = Regex("""^\s*'?([a-z0-9-]+)'?: \{ d: '([^']+)'(, fill: true)? \},$""", RegexOption.MULTILINE)

    // shared/lineIcons.ts: name to SVG path data (20 x 20 box) and whether it is filled.
    fun parseLines(ts: String): List<Triple<String, String, Boolean>> = line.findAll(ts).map { Triple(it.groupValues[1], it.groupValues[2], it.groupValues[3].isNotEmpty()) }.toList()

    fun generate(css: String, pkg: String, lines: String = ""): String = buildString {
        appendLine("// Generated by ./gradlew generateIcons from @vscode/codicons codicon.css and shared/lineIcons.ts. Do not edit.")
        appendLine("package $pkg")
        appendLine()
        appendLine("object Codicons {")
        appendLine("    private const val TABLE = \"\"\"")
        parse(css).forEach { (name, code) -> appendLine("$name ${code.toString(16)}") }
        appendLine("\"\"\"")
        appendLine()
        appendLine("    val codepoints: Map<String, Int> = TABLE.trim().lines().associate { l -> l.substringBefore(' ') to l.substringAfter(' ').toInt(16) }")
        appendLine()
        appendLine("    // Thin outline glyphs (shared/lineIcons.ts) that replace the codicon of the same name: SVG path data in a 20 x 20 box, and whether it is filled.")
        appendLine("    val lines: Map<String, Pair<String, Boolean>> = mapOf(")
        parseLines(lines).forEach { (name, d, fill) -> appendLine("        \"$name\" to (\"$d\" to $fill),") }
        appendLine("    )")
        appendLine("}")
    }
}
