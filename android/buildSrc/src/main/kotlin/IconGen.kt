package no.pradhan.agentview.tokens

// Turns @vscode/codicons codicon.css into a Kotlin name to codepoint table. The css has the aliases (clock, git-branch) that codicon.csv leaves out.
object IconGen {
    private val rule = Regex("""\.codicon-([a-z0-9-]+):before\s*\{\s*content:\s*"\\([0-9a-f]+)"""")

    fun parse(css: String): List<Pair<String, Int>> = rule.findAll(css).map { it.groupValues[1] to it.groupValues[2].toInt(16) }.toList()

    fun generate(css: String, pkg: String): String = buildString {
        appendLine("// Generated by ./gradlew generateIcons from @vscode/codicons codicon.css. Do not edit.")
        appendLine("package $pkg")
        appendLine()
        appendLine("object Codicons {")
        appendLine("    private const val TABLE = \"\"\"")
        parse(css).forEach { (name, code) -> appendLine("$name ${code.toString(16)}") }
        appendLine("\"\"\"")
        appendLine()
        appendLine("    val codepoints: Map<String, Int> = TABLE.trim().lines().associate { l -> l.substringBefore(' ') to l.substringAfter(' ').toInt(16) }")
        appendLine("}")
    }
}
